"""Offline resumable M3.1.1 fixture/schema/performance validation.

Resume via identical command; completed stages reuse only matching fingerprints.
No oracle execution, network, OCR or battle replay. Benchmarks are cached per code.
"""
from copy import deepcopy
import argparse
import hashlib
import json
from pathlib import Path
import sys
from time import perf_counter

ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from damage.inverse import infer_attack_stat
from damage.inverse_cli import solve


def canonical(value): return json.dumps(value,sort_keys=True,separators=(',',':'),allow_nan=False)
def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def atomic(path,value):
    path.parent.mkdir(parents=True,exist_ok=True)
    temporary=path.with_suffix('.tmp');temporary.write_text(json.dumps(value,indent=2)+'\n');temporary.replace(path)


def observation(group,oid='hit1'):
    return dict(id=oid,battle_id='synthetic',attacker_instance_id='opponent:1',target_instance_id='self:1',
                stat_epoch='original',damage=group['damage'],damage_kind='direct_move_damage',
                evidence='Synthetic direct damage generated by pinned independent oracle; no HP-change attribution.',input=deepcopy(group['input']))


def run(schema_library=None):
    fixture=ROOT/'tests/fixtures/inverse_damage';manifest=json.loads((fixture/'manifest.json').read_text())
    for name,expected in manifest['files'].items(): assert digest(ROOT/name)==expected,name
    dependencies=['damage/inverse.py','damage/inverse_cli.py','damage/engine.py','damage/core.py','damage/data.py',
                  'damage/data/manifest.json','damage/data/reference-v1.json','knowledge/data/manifest.json',
                  'damage/schemas/inverse-request-v1.json','damage/schemas/inverse-response-v1.json',
                  'tests/fixtures/inverse_damage/manifest.json','scripts/validate_inverse_damage.py']
    hashes={p:digest(ROOT/p) for p in dependencies}
    fingerprint=hashlib.sha256(canonical(hashes).encode()).hexdigest()
    cache=ROOT/'.cache/m311';checkpoint=cache/'validation.json'
    previous=json.loads(checkpoint.read_text()) if checkpoint.exists() else {}
    path=checkpoint if previous.get('fingerprint') in (None,fingerprint) else cache/('validation-'+fingerprint[:12]+'.json')
    if path.exists(): previous=json.loads(path.read_text())
    completed=previous.get('completed',{}) if previous.get('fingerprint')==fingerprint else {}
    state=dict(fingerprint=fingerprint,dependency_sha256=hashes,status='running',completed=completed)
    atomic(path,state)
    incoming=outgoing=None
    if schema_library:
        sys.path.append(str(Path(schema_library).resolve()));import jsonschema
        incoming=jsonschema.Draft202012Validator(json.loads((ROOT/'damage/schemas/inverse-request-v1.json').read_text()))
        outgoing=jsonschema.Draft202012Validator(json.loads((ROOT/'damage/schemas/inverse-response-v1.json').read_text()))
        incoming.check_schema(incoming.schema);outgoing.check_schema(outgoing.schema)
    bundle=json.loads((fixture/'oracle-enumeration.json').read_text())
    schema_pairs=0
    for group in bundle['groups']:
        key='oracle:'+group['id']
        request=dict(observations=[observation(group)],candidate_stats=group['candidate_stats'],stat=group['stat'],ruleset=group['input']['profile'])
        if key in completed:
            result=completed[key]['result'];print(key,'reused',flush=True)
        else:
            result=solve(request)
            assert result['feasible']['values']==group['expected_feasible'],group['id']
            completed[key]=dict(status='complete',result=result);atomic(path,state)
            print(key,'complete',flush=True)
        assert result['feasible']['values']==group['expected_feasible']
        oracle={r['candidate']:r['rolls'] for r in group['oracle_rolls']}
        for row in result['scenarios'][0]['per_observation'][0]['compatibility']:
            assert row['supported_rolls']==oracle[row['candidate']]
        if incoming:
            incoming.validate(request);outgoing.validate(result);schema_pairs+=1
    # Small representative benchmark stages, exactly 200 candidate integers.
    template=bundle['groups'][0]
    first=observation(template);first['damage']=35
    second=deepcopy(first);second['id']='hit2';second['input']['attacker']['stages']['attack']=2;second['damage']=70
    third=deepcopy(first);third['id']='hit3';third['input']['field']['reflect']=True;third['damage']={'minimum':16,'maximum':20}
    workloads=[('single',[first],[]),('multi',[first,second,third],[]),
               ('scenarios',[first,second],[dict(id='screen',scope='shared',observation_ids=['hit1','hit2'],path='field.reflect',values=[False,True])])]
    for name,observations,variables in workloads:
        key='benchmark:'+name
        request=dict(observations=observations,candidate_stats={'minimum':50,'maximum':249},ruleset=template['input']['profile'],variables=variables)
        if key not in completed:
            start=perf_counter();result=solve(request);elapsed=perf_counter()-start
            assert result['status'] in ('exact','conditional') and 100 in result['feasible']['values'],result
            completed[key]=dict(status='complete',seconds=elapsed,work=result['work'],feasible=result['feasible']);atomic(path,state)
            print(key,'complete',elapsed,flush=True)
        else:
            print(key,'reused',completed[key]['seconds'],flush=True)
        if incoming:
            incoming.validate(request);outgoing.validate(solve(request));schema_pairs+=1
    if incoming:
        # Exercise success, conditional, empty and diagnostic response contracts.
        base=dict(observations=[deepcopy(first)],candidate_stats=[100],ruleset=template['input']['profile'])
        contracts=[]
        exact=deepcopy(base);contracts.append(exact)
        empty=deepcopy(base);empty['observations'][0]['damage']=60000;contracts.append(empty)
        unknown=deepcopy(base);unknown['observations'][0]['input']['attacker']['item']=None;contracts.append(unknown)
        unsupported=deepcopy(base);unsupported['observations'][0]['input']['move']='Foul Play';contracts.append(unsupported)
        interval=deepcopy(base);interval['observations'][0]['damage']={'minimum':34,'maximum':36};contracts.append(interval)
        shared=deepcopy(base);shared['observations'].append(deepcopy(first));shared['observations'][1]['id']='hit2';shared['observations'][1]['damage']=47
        for obs in shared['observations']: obs['input']['attacker']['item']=None
        shared['variables']=[dict(id='item',scope='shared',observation_ids=['hit1','hit2'],path='attacker.item',values=['none','Life Orb'])]
        contracts.append(shared)
        local=deepcopy(shared);local['variables'][0]['scope']='observation';contracts.append(local)
        for request in contracts:
            incoming.validate(request);outgoing.validate(solve(request));schema_pairs+=1
        for invalid in [dict(base,unexpected=True),dict(base,candidate_stats=[]),dict(base,stat='defense')]:
            assert not incoming.is_valid(invalid)
            outgoing.validate(solve(invalid) if 'unexpected' not in invalid else infer_attack_stat(observations=[],candidate_stats=[]))
    state.update(status='complete',independent_groups=len(bundle['groups']),independent_forward_rows=manifest['oracle_evaluations'],schema_pairs=schema_pairs)
    atomic(path,state)
    # Stable pointer plus historical versioned checkpoints are preserved.
    atomic(cache/'latest-validation.json',dict(path=str(path.relative_to(ROOT)),fingerprint=fingerprint,status='complete'))
    print(json.dumps(dict(status=state['status'],independent_groups=state['independent_groups'],independent_forward_rows=state['independent_forward_rows'],schema_pairs=schema_pairs,manifest=str(path.relative_to(ROOT)))))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--schema-library');args=parser.parse_args()
    try:
        run(args.schema_library)
    except Exception as exc:
        atomic(ROOT/'.cache/m311/last-validation-error.json',dict(status='failed',error_type=type(exc).__name__,
            reason=str(exc),validator_sha256=digest(Path(__file__)),
            resume='Repeat scripts/validate_inverse_damage.py with the same arguments; successful stage checkpoints remain intact.'))
        raise
